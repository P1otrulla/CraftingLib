plugins {
    id("craftinglib-paper")
    id("craftinglib-publish")
}

description = "Bukkit/Paper implementation of CraftingLib (1.8+)"

dependencies {
    api(project(":craftinglib-core"))
}

// CraftingLibVersion.VERSION for bStats: a constant survives shading and relocation, unlike manifest entries.
val generateVersionClass by tasks.registering {
    val libraryVersion = project.version.toString()
    val outputDirectory = layout.buildDirectory.dir("generated/sources/craftinglib-version")

    inputs.property("version", libraryVersion)
    outputs.dir(outputDirectory)

    doLast {
        val file = outputDirectory.get().file("dev/piotrulla/craftinglib/bukkit/metrics/CraftingLibVersion.java").asFile
        file.parentFile.mkdirs()
        file.writeText(
            """
            |package dev.piotrulla.craftinglib.bukkit.metrics;
            |
            |/**
            | * Generated by Gradle from the project version.
            | */
            |public final class CraftingLibVersion {
            |
            |    public static final String VERSION = "$libraryVersion";
            |
            |    private CraftingLibVersion() {
            |    }
            |}
            |""".trimMargin()
        )
    }
}

sourceSets.main {
    java.srcDir(generateVersionClass)
}
